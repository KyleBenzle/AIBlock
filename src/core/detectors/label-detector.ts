import type { Category } from '../../types';
import { adContainer, findMediaContainer, findTextContainer, isSafeTarget, mediaKind, refineCategory } from './container';
import { norm } from './text-scan';
import type { Candidate, Detector } from './types';

export const GENERATORS =
  "AI|an AI|artificial intelligence|generative AI|Midjourney|DALL[·\\-‐ .]?E(?: ?\\d)?|Stable Diffusion|SDXL|Adobe Firefly|Firefly|Imagen|Gemini|ChatGPT|GPT-4o|GPT-\\d|Sora|Runway(?:ML)?|Leonardo(?:\\.ai)?|Ideogram|Flux|Grok|Aurora|Copilot Designer|Bing Image Creator|Image Creator|Veo|Kling|Pika|Suno|Udio|ElevenLabs|NovelAI|Nano Banana";

/** Whole short label, e.g. a badge reading "AI-generated". */
const SHORT_LABEL = new RegExp(
  '^(?:\\(?(?:AI[- ]generated|AI[- ]created|Generated by AI|Generated with AI|Made with AI|Created with AI|Created by AI|Synthetic (?:media|content|image|video|voice))(?: (?:image|content|video|photo|art|imagery|illustration|music|audio|voice|text|answer|summary))?\\)?\\.?)$',
  'i',
);

const VERB = '(?:generated|created|made|produced|rendered|illustrated|composed|voiced|narrated|written)';
const MEDIA_WORD = '(?:image|illustration|photo|picture|art|artwork|graphic|video|clip|audio|voice|music|song|track|credit)s?';

/** Anywhere-match, used only in caption/credit contexts (figcaption, credits, alt text). */
const CREDIT_ANY = new RegExp(
  `\\b${VERB}\\s+(?:entirely\\s+|fully\\s+)?(?:by|with|using|via|in)\\s+(?:${GENERATORS})\\b|\\b${MEDIA_WORD}\\s*(?:credit)?\\s*[:|/–-]\\s*(?:${GENERATORS})\\b|\\bAI[- ]generated\\b`,
  'i',
);

/** Start-anchored credit line that may appear in any short element, e.g. "Image: Midjourney". */
const CREDIT_LINE = new RegExp(
  `^\\(?(?:${MEDIA_WORD}\\s*(?:credit)?\\s*[:|/–-]\\s*(?:(?:AI[- ]generated|${VERB})\\s+(?:by|with|using|via|in)\\s+)?(?:${GENERATORS})\\b|(?:this\\s+${MEDIA_WORD}\\s+(?:was|is)\\s+)?${VERB}\\s+(?:entirely\\s+|fully\\s+)?(?:by|with|using|via|in)\\s+(?:${GENERATORS})\\b)`,
  'i',
);

const CAPTION_CONTEXT = 'figcaption, small, cite, [class*="caption" i], [class*="credit" i], [class*="attribution" i], [class*="disclaimer" i], [class*="disclosure" i]';
const isCaption = (el: Element) => !!el.closest(CAPTION_CONTEXT);

/** Disclosure that a whole article/post was produced by AI. */
const ARTICLE_DISCLOSURE = new RegExp(
  `\\b(?:this|the)\\s+(?:article|post|story|content|review|summary|text|piece|page|answer|description)\\s+(?:was|is|has been)\\s+(?:entirely\\s+|fully\\s+|automatically\\s+)?(?:generated|written|created|produced)\\s+(?:by|with|using)\\s+(?:${GENERATORS}|a large language model|an? LLM)\\b`,
  'i',
);
const ASSISTED = /\b(?:with the (?:help|assistance|aid) of (?:AI|artificial intelligence|generative AI|ChatGPT)|AI[- ]assisted (?:writing|content|article))\b/i;

function forLabel(anchor: Element, text: string, score: number, explicit: boolean, reason: string): Candidate | null {
  const ad = adContainer(anchor);
  const media = findMediaContainer(anchor);
  let target: Element | null = ad ?? media ?? findTextContainer(anchor);
  if (!target) return null;
  let category: Category = ad ? 'advertisement' : media ? (mediaKind(media) ?? 'image') : 'text';
  category = refineCategory(target, category);
  return {
    target,
    category,
    evidence: { source: 'label', type: 'visible-label', score, reason: `${reason}: "${text.slice(0, 80)}"`, explicit },
  };
}

function disclosure(text: string, el: Element, out: Candidate[]): boolean {
  const m = ARTICLE_DISCLOSURE.exec(text);
  const assisted = !m && ASSISTED.test(text);
  if (!m && !assisted) return false;
  const target = findTextContainer(el, true);
  if (target)
    out.push({
      target,
      category: refineCategory(target, 'text'),
      evidence: m
        ? { source: 'label', type: 'disclosure', score: 93, reason: `AI authorship disclosure: "${m[0]}"`, explicit: true }
        : { source: 'label', type: 'assisted-disclosure', score: 65, reason: 'Disclosure of AI-assisted writing' },
    });
  return true;
}

export const labelDetector: Detector = (input) => {
  const out: Candidate[] = [];
  for (const t of input.shortTexts) {
    const el = t.parentElement;
    if (!el) continue;
    const text = norm(t);
    if (SHORT_LABEL.test(text)) {
      const c = forLabel(el, text, 96, true, 'Explicit AI label');
      if (c) out.push(c);
    } else if (disclosure(text, el, out)) {
      continue;
    } else if (text.length <= 120 && (CREDIT_LINE.test(text) || (isCaption(el) && CREDIT_ANY.test(text)))) {
      const c = forLabel(el, text, 92, true, 'AI attribution in caption/credit');
      if (c) out.push(c);
    }
  }
  for (const t of input.longTexts) {
    const el = t.parentElement;
    if (!el) continue;
    const text = norm(t);
    if (disclosure(text, el, out)) continue;
    if (isCaption(el) && CREDIT_ANY.test(text)) {
      const c = forLabel(el, text, 92, true, 'AI attribution in caption');
      if (c) out.push(c);
    }
  }
  // Media alt/title text.
  const root = input.root as ParentNode & Node;
  const media = [...root.querySelectorAll('img[alt], img[title], video[title], video[aria-label], audio[title]')];
  if (root.nodeType === 1 && (root as Element).matches('img[alt], img[title]')) media.push(root as Element);
  for (const m of media) {
    const text = `${m.getAttribute('alt') ?? ''} ${m.getAttribute('title') ?? ''} ${m.getAttribute('aria-label') ?? ''}`.trim();
    if (text.length > 400 || !(SHORT_LABEL.test(text) || CREDIT_ANY.test(text))) continue;
    const container = findMediaContainer(m, 2);
    const target = adContainer(m) ?? (container && container.querySelectorAll('img, video, audio').length === 1 ? container : m);
    if (!isSafeTarget(target)) continue;
    const cat = (mediaKind(m) ?? 'image') as Category;
    out.push({
      target,
      category: refineCategory(target, cat),
      evidence: { source: 'label', type: 'alt-text', score: 90, reason: `Media description states AI origin: "${text.slice(0, 80)}"`, explicit: true },
      fingerprint: (m as HTMLImageElement).currentSrc || m.getAttribute('src') || undefined,
    });
  }
  return out;
};
